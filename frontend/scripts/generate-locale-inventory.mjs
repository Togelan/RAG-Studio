import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const frontendDirectory = resolve(scriptDirectory, "..")
const localeDirectory = resolve(frontendDirectory, "..", "src", "api", "locales")
const outputDirectory = resolve(frontendDirectory, "src", "i18n")

function assertLocaleMap(value, locale) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${locale}.json must contain a translation object`)
  }

  const entries = Object.entries(value)
  if (
    entries.length === 0 ||
    entries.some(
      ([key, translation]) => !key || typeof translation !== "string" || !translation.trim(),
    )
  ) {
    throw new Error(`${locale}.json must contain non-empty string keys and translations`)
  }

  return entries.map(([key]) => key).sort()
}

function assertEqualKeys(expected, actual, locale) {
  if (expected.length !== actual.length || expected.some((key, index) => key !== actual[index])) {
    throw new Error(`${locale}.json keys must exactly match en.json`)
  }
}

function createTypeScriptInventory(keys) {
  const serializedKeys = JSON.stringify(keys, null, 2).replace("\n]", ",\n]")

  return `// Generated by scripts/generate-locale-inventory.mjs from src/api/locales/*.json.\n// Do not hand-edit: backend locale JSON remains the translation authority.\n\nexport const supportedLocales = ["en", "ru"] as const\n\nexport type Locale = (typeof supportedLocales)[number]\n\nexport const localeKeys = ${serializedKeys} as const\n\nexport type TranslationKey = (typeof localeKeys)[number]\n\nexport const localeInventory = {\n  en: localeKeys,\n  ru: localeKeys,\n} as const satisfies Readonly<Record<Locale, readonly TranslationKey[]>>\n`
}

async function loadLocale(locale) {
  const source = await readFile(resolve(localeDirectory, `${locale}.json`), "utf8")
  return assertLocaleMap(JSON.parse(source), locale)
}

const englishKeys = await loadLocale("en")
const russianKeys = await loadLocale("ru")
assertEqualKeys(englishKeys, russianKeys, "ru")

await writeFile(
  resolve(outputDirectory, "locale-inventory.json"),
  `${JSON.stringify({ en: englishKeys, ru: russianKeys }, null, 2)}\n`,
  "utf8",
)
await writeFile(
  resolve(outputDirectory, "locale-inventory.ts"),
  createTypeScriptInventory(englishKeys),
  "utf8",
)

console.log(`Generated exact EN/RU locale inventory with ${englishKeys.length} keys.`)
